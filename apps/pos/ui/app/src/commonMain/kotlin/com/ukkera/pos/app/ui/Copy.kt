@Composable
internal fun copy(key: Copy, vararg args: Any): String =
    stringResource(if (LocalAppLanguage.current == AppLanguage.ARABIC) key.ar else key.en, *args)

@Composable
internal fun basketItemCount(count: Int): String {
    val language = LocalAppLanguage.current
    val cardinal = if (language == AppLanguage.ARABIC) arabicCardinal(count) else if (count == 1) ArabicCardinal.ONE else ArabicCardinal.OTHER
    val resource = when (cardinal) {
        ArabicCardinal.ZERO -> Copy.BASKET_COUNT_ZERO
        ArabicCardinal.ONE -> Copy.BASKET_COUNT_ONE
        ArabicCardinal.TWO -> Copy.BASKET_COUNT_TWO
        ArabicCardinal.FEW -> Copy.BASKET_COUNT_FEW
        ArabicCardinal.MANY -> Copy.BASKET_COUNT_MANY
        ArabicCardinal.OTHER -> Copy.BASKET_COUNT_OTHER
    }
    return copy(resource, language.digits(count.toString()))
}
