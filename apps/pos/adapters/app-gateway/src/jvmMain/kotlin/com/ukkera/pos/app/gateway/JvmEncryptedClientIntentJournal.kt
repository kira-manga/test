private fun checkRootEntries(directory: Path, allowedTemporary: String? = null) {
    val allowed = setOf(MANIFEST_FILE, LOCK_FILE, ARCHIVE_DIRECTORY, allowedTemporary)
    Files.newDirectoryStream(directory).use { entries -> for (entry in entries) check(entry.fileName.toString() in allowed) }
}

private fun validateDirectory(directory: Path) {
    check(directory.isAbsolute && directory.normalize() == directory && directory.toRealPath() == directory)
    check(Files.isDirectory(directory, LinkOption.NOFOLLOW_LINKS))
    val permissions = Files.getPosixFilePermissions(directory, LinkOption.NOFOLLOW_LINKS)
    check(permissions == PosixFilePermissions.fromString("rwx------"))
}

private fun validatePrivateFile(path: Path) {
    check(Files.isRegularFile(path, LinkOption.NOFOLLOW_LINKS))
    val permissions = Files.getPosixFilePermissions(path, LinkOption.NOFOLLOW_LINKS)
    check(permissions.isNotEmpty() && permissions.all { it == PosixFilePermission.OWNER_READ || it == PosixFilePermission.OWNER_WRITE })
    check(PosixFilePermission.OWNER_READ in permissions && PosixFilePermission.OWNER_WRITE in permissions)
}

private fun fileKey(path: Path): Any = Files.readAttributes(path, BasicFileAttributes::class.java,
    LinkOption.NOFOLLOW_LINKS).fileKey() ?: error("client.file.identity.unavailable")

private fun forceDirectory(directory: Path) {
    FileChannel.open(directory, StandardOpenOption.READ).use { it.force(true) }
}

private fun readFile(path: Path, maximumBytes: Int): ByteArray {
    validatePrivateFile(path)
    return FileChannel.open(path, setOf<OpenOption>(StandardOpenOption.READ, LinkOption.NOFOLLOW_LINKS)).use { channel ->
        val size = channel.size()
        check(size in 1..maximumBytes.toLong())
        val value = ByteArray(size.toInt())
        try {
            val buffer = ByteBuffer.wrap(value)
            while (buffer.hasRemaining()) check(channel.read(buffer) > 0)
            check(channel.size() == size)
            value
        } catch (failure: Exception) { value.fill(0); throw failure }
    }
}
