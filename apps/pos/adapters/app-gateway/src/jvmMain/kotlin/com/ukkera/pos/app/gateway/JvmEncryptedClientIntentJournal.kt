/**
 * Trusted platform-owned observation, not a UI claim or a file-exists authorization shortcut.
 * The root qualifies directory/key custody, no copied/rolled-back journal and this process
 * lifetime. A SecretKey may be a non-exporting provider handle; no adjacent raw key is accepted
 * or generated by this implementation. A new process obtains a new contextId, not a new journalId.
 */
public class JvmClientJournalCustodyView(
    public val directory: Path,
    public val owner: LocalClientIdentity,
    public val journalId: DomainId,
    public val keyId: DomainId,
    public val processContextId: DomainId,
    public val key: SecretKey,
    private val currentLifetime: () -> Boolean,
) {
    public fun isCurrent(): Boolean = currentLifetime()
    override fun toString(): String = "JvmClientJournalCustodyView([REDACTED])"
}

/** Every call must obtain current protected service-context custody, or return null. */
public fun interface JvmClientJournalCustody {
    public fun current(): JvmClientJournalCustodyView?
}

public sealed interface JvmClientJournalOpenResult {
    public class Opened(public val journal: JvmEncryptedClientIntentJournal) : JvmClientJournalOpenResult
    public data object Unavailable : JvmClientJournalOpenResult
}

/**
 * Actual JVM encrypted durable client intent storage. An exclusively locked, private directory
 * holds ONE bounded encrypted active manifest. Archive-before-removal makes interrupted explicit
 * acknowledgement retain the same queue identity. Missing/corrupt/unknown files never initialize
 * an empty journal, and uncertain IO permanently retires this instance without deleting evidence.
 *
 * POSIX private paths, AES-GCM and atomic replace + file/parent-directory fsync are required;
 * unsupported providers/filesystems fail closed. These primitives are neither rollback proof,
 * protected physical-money recording capacity, nor fencing of a different branch master.
 */
public class JvmEncryptedClientIntentJournal private constructor(
    owner: LocalClientIdentity,
    private val custody: JvmClientJournalCustody,
    private val directory: Path,
    private val journalId: DomainId,
    private val keyId: DomainId,
    private val processContextId: DomainId,
    private val directoryKey: Any,
    private val lockKey: Any,
    private val channel: FileChannel,
    private val fileLock: FileLock,
) : LocalClientIntentJournal(owner) {
    private val mutex = ReentrantLock()
    private val closed = AtomicBoolean(false)
    private val failed = AtomicBoolean(false)
    private val random = SecureRandom()
    private var expectedHead: PayloadDigest? = null

    override internal suspend fun find(operationId: OperationId): JournalRead<StoredClientIntentV1?> = access {
        val manifest = readManifest()
        JournalRead.Value(manifest.entries.singleOrNull { it.operationId == operationId } ?: readArchive(operationId))
    } ?: JournalRead.Unavailable

    override internal suspend fun pending(): JournalRead<List<StoredClientIntentV1>> = access {
        JournalRead.Value(readManifest().entries.sortedBy { it.operationId.value })
    } ?: JournalRead.Unavailable

    override internal suspend fun documentarySource(documentId: DomainId): JournalRead<StoredClientDocumentarySourceV1?> = access {
        JournalRead.Value(readManifest().sourceRecords.singleOrNull { it.documentId == documentId })
    } ?: JournalRead.Unavailable

    override internal suspend fun documentarySources(): JournalRead<List<StoredClientDocumentarySourceV1>> = access {
        JournalRead.Value(readManifest().sourceRecords.sortedBy { it.documentId.value })
    } ?: JournalRead.Unavailable

    override internal suspend fun saveDocumentarySource(source: StoredClientDocumentarySourceV1): JournalWrite = access {
        val captured = encodeSource(source).useWiped(::decodeSource)
        val manifest = readManifest()
        val existing = manifest.sourceRecords.singleOrNull { it.documentId == captured.documentId }
        val operations = captured.operationIds.toSet()
        when {
            existing != null -> if (existing == captured) JournalWrite.DURABLE else JournalWrite.IDENTITY_CONFLICT
            captured.completionAttemptCount != 1 -> JournalWrite.IDENTITY_CONFLICT
            manifest.entries.any { it.operationId in operations } || manifest.sourceRecords.any { retained ->
                retained.operationIds.any { it in operations }
            } || operations.any { readArchive(it) != null } -> JournalWrite.IDENTITY_CONFLICT
            manifest.sourceRecords.size >= MAX_CLIENT_DOCUMENTARY_SOURCES -> JournalWrite.NO_CAPACITY
            else -> { writeManifest(manifest.withSource(captured)); JournalWrite.DURABLE }
        }
    } ?: JournalWrite.UNAVAILABLE

    override internal suspend fun appendDocumentaryCompletionRetry(source: StoredClientDocumentarySourceV1): JournalWrite = access {
        val captured = encodeSource(source).useWiped(::decodeSource)
        val manifest = readManifest()
        val existing = manifest.sourceRecords.singleOrNull { it.documentId == captured.documentId }
        val newOperationId = captured.latestCompleteOperationId
        when {
            existing == null || captured.completionAttemptCount == 1 -> JournalWrite.IDENTITY_CONFLICT
            existing == captured -> JournalWrite.DURABLE
            !captured.isOneCompletionAppendOf(existing) -> JournalWrite.IDENTITY_CONFLICT
            existing.completionAttemptCount >= MAX_CLIENT_DOCUMENTARY_COMPLETION_ATTEMPTS -> JournalWrite.NO_CAPACITY
            manifest.entries.any { it.operationId == newOperationId } ||
                manifest.sourceRecords.any { newOperationId in it.operationIds } || readArchive(newOperationId) != null ->
                JournalWrite.IDENTITY_CONFLICT
            manifest.entries.any { it.operationId != existing.latestCompleteOperationId } -> JournalWrite.UNAVAILABLE
            else -> {
                val previous = manifest.entries.singleOrNull { it.operationId == existing.latestCompleteOperationId }
                    ?: readArchive(existing.latestCompleteOperationId) ?: return@access JournalWrite.UNAVAILABLE
                if (!existing.hasClosedStaleCompletion(previous)) return@access JournalWrite.UNAVAILABLE
                writeManifest(manifest.replaceSource(captured))
                JournalWrite.DURABLE
            }
        }
    } ?: JournalWrite.UNAVAILABLE

    override internal suspend fun stage(intent: StoredClientIntentV1): JournalWrite = access {
        intent.validate(owner)
        check(intent.localPhase == LocalPendingPhase.STAGED && !intent.acknowledged)
        val manifest = readManifest()
        val existing = manifest.entries.singleOrNull { it.operationId == intent.operationId } ?: readArchive(intent.operationId)
        val source = manifest.sourceFor(intent.operationId)
        when {
            source != null && !source.accepts(intent) -> JournalWrite.IDENTITY_CONFLICT
            intent.documentaryCommand() && source == null -> JournalWrite.IDENTITY_CONFLICT
            existing != null -> if (existing.sameIntent(intent)) JournalWrite.DURABLE else JournalWrite.IDENTITY_CONFLICT
            manifest.entries.size >= MAX_CLIENT_PENDING -> JournalWrite.NO_CAPACITY // no write/dispatch occurred
            else -> { writeManifest(manifest.next(entries = manifest.entries + intent)); JournalWrite.DURABLE }
        }
    } ?: JournalWrite.UNAVAILABLE

    override internal suspend fun markDispatched(operationId: OperationId): JournalWrite = access {
        val manifest = readManifest()
        val entry = manifest.entries.singleOrNull { it.operationId == operationId }
            ?: readArchive(operationId) ?: error("client.intent.required")
        manifest.validateSource(entry)
        if (entry.actionApproval != null && entry.actionApproval.localPhase != com.ukkera.pos.app.LocalActionApprovalPhase.ATTACHED)
            return@access JournalWrite.UNAVAILABLE
        if (entry.localPhase == LocalPendingPhase.STAGED) writeManifest(manifest.replace(entry.copy(phase = LocalPendingPhase.DISPATCH_UNRESOLVED.name)))
        JournalWrite.DURABLE
    } ?: JournalWrite.UNAVAILABLE

    override internal suspend fun updateActionApproval(previous: StoredClientIntentV1, next: StoredClientIntentV1): JournalWrite = access {
        if (!validClientActionApprovalTransition(previous, next)) return@access JournalWrite.IDENTITY_CONFLICT
        val manifest = readManifest()
        val current = manifest.entries.singleOrNull { it.operationId == previous.operationId }
            ?: return@access JournalWrite.IDENTITY_CONFLICT
        when {
            current == next -> JournalWrite.DURABLE
            current != previous -> JournalWrite.IDENTITY_CONFLICT
            else -> { writeManifest(manifest.replace(next)); JournalWrite.DURABLE }
        }
    } ?: JournalWrite.UNAVAILABLE

    override internal suspend fun remember(operationId: OperationId, result: StoredKernelResultV1): JournalWrite = access {
        val manifest = readManifest()
        val entry = manifest.entries.singleOrNull { it.operationId == operationId }
            ?: readArchive(operationId) ?: error("client.intent.required")
        result.validate()
        check(result.operationId == operationId && result.originalActorId == owner.actorId)
        check(entry.recorded == null || entry.recorded == result) { "client.result.conflict" }
        if (entry.recorded == null) writeManifest(manifest.replace(entry.copy(
            phase = LocalPendingPhase.RECORDED_UNACKNOWLEDGED.name, recorded = result)))
        JournalWrite.DURABLE
    } ?: JournalWrite.UNAVAILABLE

    override internal suspend fun acknowledge(operationId: OperationId, result: StoredKernelResultV1): JournalWrite = access {
        val manifest = readManifest()
        val active = manifest.entries.singleOrNull { it.operationId == operationId }
        val archived = readArchive(operationId)
        if (active == null) {
            check(archived != null && archived.recorded == result && archived.acknowledged)
        } else {
            check(active.recorded != null && active.recorded == result && !active.acknowledged)
            val archivedValue = active.copy(acknowledged = true)
            if (archived != null) check(archived == archivedValue) { "client.archive.conflict" }
            else writeArchive(archivedValue)
            // The complete result archive is already durable. Interrupted removal is still pending,
            // not deletion permission; an exact repeated acknowledgement performs this same step.
            writeManifest(manifest.next(entries = manifest.entries.filterNot { it.operationId == operationId },
                archivedCount = Math.addExact(manifest.archivedCount, 1)))
        }
        JournalWrite.DURABLE
    } ?: JournalWrite.UNAVAILABLE

    override public suspend fun close() {
        closed.set(true) // suppress new interaction before waiting for any in-flight disk operation
        // Closing is ownership cleanup, not a cancellable UI operation. In particular a cancelled
        // sign-in must not strand this process's file lock after setting closed.
        withContext(NonCancellable + Dispatchers.IO) { mutex.withLock {
            try { if (fileLock.isValid) fileLock.release() } finally { channel.close() }
        } }
    }

    private suspend fun <T> access(block: () -> T): T? = withContext(Dispatchers.IO) {
        mutex.withLock {
            if (closed.get() || failed.get()) return@withLock null
            try {
                currentCustody()
                val result = block()
                currentCustody()
                result
            } catch (_: Exception) {
                failed.set(true)
                null // no exception text, key, path, request or private result escapes the boundary
            }
        }
    }

    private fun currentCustody(): JvmClientJournalCustodyView {
        check(!closed.get() && !failed.get() && fileLock.isValid && channel.isOpen)
        val current = custody.current() ?: error("client.custody.unavailable")
        check(current.owner == owner && current.journalId == journalId && current.keyId == keyId &&
            current.processContextId == processContextId && current.directory.toAbsolutePath().normalize() == directory && current.isCurrent())
        check(current.key.algorithm.equals("AES", ignoreCase = true))
        validateDirectory(directory)
        check(fileKey(directory) == directoryKey && fileKey(directory.resolve(LOCK_FILE)) == lockKey)
        validatePrivateFile(directory.resolve(LOCK_FILE))
        validateDirectory(directory.resolve(ARCHIVE_DIRECTORY))
        checkRootEntries(directory)
        return current
    }

    private fun readManifest(): ManifestV1 {
        val bytes = readFile(directory.resolve(MANIFEST_FILE), MAX_MANIFEST_BYTES + ENVELOPE_OVERHEAD)
        return bytes.useWiped { encrypted ->
            val digest = sha256(encrypted)
            check(expectedHead == null || expectedHead == digest) { "client.head.changed" }
            val manifest = decrypt(encrypted, "manifest", MAX_MANIFEST_BYTES).useWiped { plain ->
                journalJson.decodeFromString(ManifestV1.serializer(), plain.decodeToString(throwOnInvalidSequence = true)).also { decoded ->
                    encodeManifest(decoded).useWiped { check(it.contentEquals(plain)) }
                }
            }
            validateArchives(manifest)
            expectedHead = digest
            manifest
        }
    }

    private fun writeManifest(value: ManifestV1) {
        encodeManifest(value).useWiped { encrypt(it, "manifest") }.useWiped { encrypted ->
            atomicWrite(directory.resolve(MANIFEST_FILE), encrypted)
            expectedHead = sha256(encrypted)
        }
    }

    private fun encodeManifest(value: ManifestV1): ByteArray {
        value.validate(owner, journalId, keyId)
        val bytes = journalJson.encodeToString(ManifestV1.serializer(), value).encodeToByteArray(throwOnInvalidSequence = true)
        try { check(bytes.size in 1..MAX_MANIFEST_BYTES); return bytes }
        catch (failure: Throwable) { bytes.fill(0); throw failure }
    }

    /** Every retained archive participates, including an interrupted acknowledgement duplicate. */
    private fun validateArchives(manifest: ManifestV1) {
        var count = 0L
        var duplicates = 0L
        val requiredCompletions = buildMap<OperationId, StoredClientDocumentarySourceV1> {
            manifest.sourceRecords.forEach { source -> source.priorCompletionOperationIds.forEach { put(it, source) } }
        }
        val observedCompletions = mutableSetOf<OperationId>()
        manifest.entries.forEach { entry -> requiredCompletions[entry.operationId]?.let { source ->
            check(source.hasClosedStaleCompletion(entry))
            observedCompletions += entry.operationId
        } }
        Files.newDirectoryStream(directory.resolve(ARCHIVE_DIRECTORY)).use { archives ->
            for (path in archives) {
                val name = path.fileName.toString()
                check(name.endsWith(ARCHIVE_SUFFIX))
                val operationId = OperationId(name.removeSuffix(ARCHIVE_SUFFIX))
                check(path == archivePath(operationId))
                val archived = readArchive(operationId) ?: error("client.archive.required")
                manifest.validateSource(archived)
                requiredCompletions[operationId]?.let { source ->
                    check(source.hasClosedStaleCompletion(archived))
                    observedCompletions += operationId
                }
                val active = manifest.entries.singleOrNull { it.operationId == operationId }
                if (active != null) {
                    check(active.recorded != null && !active.acknowledged && archived == active.copy(acknowledged = true))
                    duplicates = Math.addExact(duplicates, 1L)
                }
                count = Math.addExact(count, 1L)
            }
        }
        check(count == Math.addExact(manifest.archivedCount, duplicates))
        check(observedCompletions == requiredCompletions.keys)
    }

    private fun archivePath(operationId: OperationId): Path = directory.resolve(ARCHIVE_DIRECTORY).resolve(operationId.value + ARCHIVE_SUFFIX)

    private fun readArchive(operationId: OperationId): StoredClientIntentV1? {
        val path = archivePath(operationId)
        if (!Files.exists(path, LinkOption.NOFOLLOW_LINKS)) {
            // Distinguish an actual missing name from a permission/provider failure.
            if (Files.notExists(path, LinkOption.NOFOLLOW_LINKS)) return null
            error("client.archive.unavailable")
        }
        return readFile(path, MAX_CLIENT_ENTRY_BYTES + ENVELOPE_OVERHEAD).useWiped { encrypted ->
            decrypt(encrypted, "archive/${operationId.value}", MAX_CLIENT_ENTRY_BYTES).useWiped { plain ->
                journalJson.decodeFromString(StoredClientIntentV1.serializer(), plain.decodeToString(throwOnInvalidSequence = true)).also { entry ->
                    check(entry.operationId == operationId && entry.acknowledged && entry.recorded != null)
                    encodeEntry(entry).useWiped { check(it.contentEquals(plain)) }
                }
            }
        }
    }

    private fun writeArchive(value: StoredClientIntentV1) {
        val path = archivePath(value.operationId)
        check(Files.notExists(path, LinkOption.NOFOLLOW_LINKS))
        encodeEntry(value).useWiped {
            encrypt(it, "archive/${value.operationId.value}")
        }.useWiped { atomicWrite(path, it) }
    }

    private fun encodeEntry(entry: StoredClientIntentV1): ByteArray {
        entry.validate(owner)
        val bytes = journalJson.encodeToString(StoredClientIntentV1.serializer(), entry).encodeToByteArray(throwOnInvalidSequence = true)
        try { check(bytes.size in 1..MAX_CLIENT_ENTRY_BYTES); return bytes }
        catch (failure: Throwable) { bytes.fill(0); throw failure }
    }

    private fun encodeSource(source: StoredClientDocumentarySourceV1): ByteArray {
        source.validate(owner)
        val bytes = journalJson.encodeToString(StoredClientDocumentarySourceV1.serializer(), source)
            .encodeToByteArray(throwOnInvalidSequence = true)
        try { check(bytes.size in 1..MAX_CLIENT_DOCUMENTARY_SOURCE_BYTES); return bytes }
        catch (failure: Throwable) { bytes.fill(0); throw failure }
    }

    private fun decodeSource(bytes: ByteArray): StoredClientDocumentarySourceV1 {
        check(bytes.size in 1..MAX_CLIENT_DOCUMENTARY_SOURCE_BYTES)
        val source = journalJson.decodeFromString(StoredClientDocumentarySourceV1.serializer(),
            bytes.decodeToString(throwOnInvalidSequence = true))
        encodeSource(source).useWiped { check(it.contentEquals(bytes)) }
        return source
    }

    private fun aad(purpose: String): ByteArray = listOf("ukkera.client-intents/v1", owner.scope.organizationId.value,
        owner.scope.companyId.value, owner.scope.branchId.value, owner.actorId.value, owner.deviceId.value,
        journalId.value, keyId.value, purpose).joinToString("\n").encodeToByteArray()

    private fun encrypt(plain: ByteArray, purpose: String): ByteArray {
        val context = currentCustody()
        val nonce = ByteArray(12).also(random::nextBytes)
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(Cipher.ENCRYPT_MODE, context.key, GCMParameterSpec(128, nonce))
        aad(purpose).useWiped(cipher::updateAAD)
        val ciphertext = cipher.doFinal(plain)
        check(context.isCurrent())
        return ByteBuffer.allocate(4 + nonce.size + ciphertext.size).putInt(MAGIC).put(nonce).put(ciphertext).array()
    }

    private fun decrypt(encrypted: ByteArray, purpose: String, maximum: Int): ByteArray {
        check(encrypted.size in ENVELOPE_OVERHEAD..(maximum + ENVELOPE_OVERHEAD))
        val context = currentCustody()
        val buffer = ByteBuffer.wrap(encrypted)
        check(buffer.int == MAGIC)
        val nonce = ByteArray(12).also(buffer::get)
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(Cipher.DECRYPT_MODE, context.key, GCMParameterSpec(128, nonce))
        aad(purpose).useWiped(cipher::updateAAD)
        val result = cipher.doFinal(encrypted, 16, encrypted.size - 16)
        if (!context.isCurrent()) { result.fill(0); error("client.custody.ended") }
        return result
    }

    private fun atomicWrite(destination: Path, bytes: ByteArray) {
        currentCustody()
        val temporary = directory.resolve(".pending-${DomainId.random().value}.tmp")
        FileChannel.open(temporary, setOf<OpenOption>(StandardOpenOption.CREATE_NEW, StandardOpenOption.WRITE, LinkOption.NOFOLLOW_LINKS),
            PosixFilePermissions.asFileAttribute(PosixFilePermissions.fromString("rw-------"))).use { file ->
            val buffer = ByteBuffer.wrap(bytes)
            while (buffer.hasRemaining()) check(file.write(buffer) > 0)
            file.force(true)
        }
        // currentCustody's root listing deliberately treats leftover temporary names as unknown;
        // validate its identity before rename without hiding this transaction's own new file.
        currentCustodyDuringWrite(temporary)
        Files.move(temporary, destination, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING)
        forceDirectory(destination.parent)
        if (destination.parent != directory) forceDirectory(directory)
        currentCustody()
    }

    private fun currentCustodyDuringWrite(temporary: Path) {
        val context = custody.current() ?: error("client.custody.unavailable")
        check(!closed.get() && !failed.get() && fileLock.isValid && context.isCurrent() &&
            context.owner == owner && context.journalId == journalId && context.keyId == keyId &&
            context.processContextId == processContextId && context.directory.toAbsolutePath().normalize() == directory)
        check(fileKey(directory) == directoryKey && fileKey(directory.resolve(LOCK_FILE)) == lockKey)
        validatePrivateFile(temporary)
        checkRootEntries(directory, temporary.fileName.toString())
    }

    public companion object {
        /** Explicit initial ceremony only: the already protected directory must be genuinely empty. */
        public suspend fun createNew(custody: JvmClientJournalCustody): JvmClientJournalOpenResult = open(custody, true)

        /** Never creates, repairs, deletes an unknown tail, or replaces a missing journal. */
        public suspend fun openExisting(custody: JvmClientJournalCustody): JvmClientJournalOpenResult = open(custody, false)

        private suspend fun open(custody: JvmClientJournalCustody, create: Boolean): JvmClientJournalOpenResult {
            var channel: FileChannel? = null
            var lock: FileLock? = null
            var handedOff = false
            try {
                val result = withContext(Dispatchers.IO) {
                    try {
                        val context = custody.current() ?: return@withContext JvmClientJournalOpenResult.Unavailable
                        check(context.isCurrent() && context.key.algorithm.equals("AES", ignoreCase = true))
                        val directory = context.directory.toAbsolutePath().normalize()
                        validateDirectory(directory)
                        if (create) Files.newDirectoryStream(directory).use { check(!it.iterator().hasNext()) }
                        else checkRootEntries(directory)
                        val lockPath = directory.resolve(LOCK_FILE)
                        val options = mutableSetOf<OpenOption>(StandardOpenOption.READ, StandardOpenOption.WRITE, LinkOption.NOFOLLOW_LINKS)
                        if (create) options += StandardOpenOption.CREATE_NEW
                        val openedChannel = FileChannel.open(lockPath, options,
                            PosixFilePermissions.asFileAttribute(PosixFilePermissions.fromString("rw-------")))
                        channel = openedChannel
                        validatePrivateFile(lockPath)
                        val openedLock = openedChannel.tryLock() ?: error("client.custody.busy")
                        lock = openedLock
                        if (create) {
                            openedChannel.force(true)
                            Files.createDirectory(directory.resolve(ARCHIVE_DIRECTORY),
                                PosixFilePermissions.asFileAttribute(PosixFilePermissions.fromString("rwx------")))
                            forceDirectory(directory)
                        }
                        val journal = JvmEncryptedClientIntentJournal(context.owner, custody, directory, context.journalId, context.keyId,
                            context.processContextId, fileKey(directory), fileKey(lockPath), openedChannel, openedLock)
                        if (create) journal.writeManifest(ManifestV1(owner = context.owner, journalId = context.journalId, keyId = context.keyId))
                        else journal.readManifest()
                        journal.currentCustody()
                        JvmClientJournalOpenResult.Opened(journal)
                    } catch (cancelled: CancellationException) { throw cancelled }
                    catch (_: Exception) { JvmClientJournalOpenResult.Unavailable }
                }
                // withContext can discard a completed IO result when the caller is cancelled at
                // the dispatch back. Only this side of that boundary transfers resource ownership.
                handedOff = result is JvmClientJournalOpenResult.Opened
                return result
            } finally {
                if (!handedOff) withContext(NonCancellable + Dispatchers.IO) {
                    try { lock?.let { if (it.isValid) it.release() } } catch (_: Exception) { }
                    try { channel?.close() } catch (_: Exception) { }
                    // Any completed manifest or interrupted-write evidence remains on disk.
                }
            }
        }
    }
}

@Serializable
@OptIn(ExperimentalSerializationApi::class)
private data class ManifestV1(
    val version: Int = 1,
    val owner: LocalClientIdentity,
    val journalId: DomainId,
    val keyId: DomainId,
    val revision: Long = 0,
    val archivedCount: Long = 0,
    val entries: List<StoredClientIntentV1> = emptyList(),
    /** No source was recorded in ordinary v1 legacy journals; reads retain their exact bytes. */
    @EncodeDefault(EncodeDefault.Mode.NEVER)
    val documentarySources: List<StoredClientDocumentarySourceV1>? = null,
) {
    val sourceRecords: List<StoredClientDocumentarySourceV1> get() = documentarySources.orEmpty()

    fun validate(owner: LocalClientIdentity, journalId: DomainId, keyId: DomainId) {
        check(version == 1 && this.owner == owner && this.journalId == journalId && this.keyId == keyId)
        check(revision >= 0 && archivedCount >= 0 && entries.size <= MAX_CLIENT_PENDING)
        check(entries.map { it.operationId }.distinct().size == entries.size && entries.none { it.acknowledged })
        check(documentarySources == null || sourceRecords.size in 1..MAX_CLIENT_DOCUMENTARY_SOURCES)
        sourceRecords.forEach { it.validate(owner) }
        check(sourceRecords.map { it.documentId }.toSet().size == sourceRecords.size)
        val operations = sourceRecords.flatMap { it.operationIds }
        check(operations.toSet().size == operations.size)
        entries.forEach { entry -> entry.validate(owner); validateSource(entry) }
    }

    fun sourceFor(operationId: OperationId): StoredClientDocumentarySourceV1? =
        sourceRecords.singleOrNull { operationId in it.operationIds }

    fun validateSource(entry: StoredClientIntentV1) {
        val source = sourceFor(entry.operationId)
        check(!entry.documentaryCommand() || source != null)
        source?.let { check(it.accepts(entry)) }
    }

    fun withSource(source: StoredClientDocumentarySourceV1): ManifestV1 =
        copy(revision = Math.addExact(revision, 1L), documentarySources = sourceRecords + source)
    fun replaceSource(source: StoredClientDocumentarySourceV1): ManifestV1 {
        check(sourceRecords.count { it.documentId == source.documentId } == 1)
        return copy(revision = Math.addExact(revision, 1L),
            documentarySources = sourceRecords.map { if (it.documentId == source.documentId) source else it })
    }
    fun next(entries: List<StoredClientIntentV1>, archivedCount: Long = this.archivedCount): ManifestV1 =
        copy(revision = Math.addExact(revision, 1), archivedCount = archivedCount, entries = entries)
    fun replace(entry: StoredClientIntentV1): ManifestV1 {
        check(entries.count { it.operationId == entry.operationId } == 1)
        return next(entries.map { if (it.operationId == entry.operationId) entry else it })
    }
}

