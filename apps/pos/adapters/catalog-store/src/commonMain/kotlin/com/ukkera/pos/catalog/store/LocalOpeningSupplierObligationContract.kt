/** Explicit migrated supplier debt. This profile creates no purchase, stock or cash record. */
public object LocalOpeningSupplierObligationProfile {
    public val COMMAND: CommandKey = CommandKey("purchasing.opening-obligation", 1)
    public val READ: ReadKey = ReadKey("purchasing.opening-obligations", 1)
    public const val OBLIGATION: String = "local.purchasing.opening-obligation"
    public const val DOCUMENT_CLAIM: String = "purchasing.opening-obligation.document"
    public const val SOURCE_CLAIM: String = "purchasing.opening-obligation.source"
    public const val SOURCE_IDENTITY_CLAIM: String = "purchasing.opening-obligation.source-identity"
    public const val REFERENCE_CLAIM: String = "purchasing.opening-obligation.reference"
    public const val RECORDED: String = "purchasing.opening_obligation_recorded"
    public const val MAX_PAGE: Int = 20
    public const val MAX_INPUT_BYTES: Int = 32_768
    public const val MAX_DOCUMENT_BYTES: Int = 4_096
    public const val DOCUMENT_MEDIA_TYPE: String = "text/plain"
    public const val DOCUMENT_PURPOSE: String = "OPENING_SUPPLIER_OBLIGATION"
    public const val DOCUMENT_RETENTION: String = "IMMUTABLE_LOCAL_ORIGINAL"
    public const val DOCUMENT_ACCESS_POLICY: String = "PURCHASING_READ_AND_INVENTORY_COST_READ"
    public const val DOCUMENT_UPLOAD_STATUS_AT_CAPTURE: String = "NOT_UPLOADED"
    internal const val MAX_RECORD_BYTES: Int = 65_536
    internal const val MAX_PAGE_BYTES: Int = 65_536
    internal const val SCHEMA: String = "local.purchasing.opening-obligation/v1"
    public fun key(id: DomainId): AggregateKey = AggregateKey(OBLIGATION, id)
}

/** Exact UTF-8 plain-text original. Identity and text are never trimmed or normalized. */
@Serializable
public data class LocalOpeningSupplierDocumentaryEvidenceV1(
    public val sourceIdentity: String,
    public val text: String,
) {
    init {
        require(sourceIdentity.length in 1..128 && sourceIdentity.isNotBlank() &&
            sourceIdentity.none { it.code < 0x20 || it.code in 0x7f..0x9f })
        sourceIdentity.encodeToByteArray(throwOnInvalidSequence = true)
        require(text.length in 1..LocalOpeningSupplierObligationProfile.MAX_DOCUMENT_BYTES &&
            text.encodeToByteArray(throwOnInvalidSequence = true).size in 1..LocalOpeningSupplierObligationProfile.MAX_DOCUMENT_BYTES)
    }
}

/** Capture facts generated by the protected master; these fields never grant read access. */
@Serializable
public data class LocalOpeningSupplierDocumentaryMetadataV1(
    public val scope: BranchScope,
    public val evidenceId: DomainId,
    public val ownerObligationId: DomainId,
    public val supplierId: DomainId,
    public val captureOperationId: OperationId,
    public val capturedBy: DomainId,
    public val capturedAt: UtcInstant,
    public val byteSize: Int,
    public val sha256: String,
    public val mediaType: String,
    public val purpose: String,
    public val retention: String,
    public val accessPolicy: String,
    public val uploadStatusAtCapture: String,
) {
    init {
        require(byteSize in 1..LocalOpeningSupplierObligationProfile.MAX_DOCUMENT_BYTES)
        PayloadDigest(sha256)
        require(mediaType == LocalOpeningSupplierObligationProfile.DOCUMENT_MEDIA_TYPE &&
            purpose == LocalOpeningSupplierObligationProfile.DOCUMENT_PURPOSE &&
            retention == LocalOpeningSupplierObligationProfile.DOCUMENT_RETENTION &&
            accessPolicy == LocalOpeningSupplierObligationProfile.DOCUMENT_ACCESS_POLICY &&
            uploadStatusAtCapture == LocalOpeningSupplierObligationProfile.DOCUMENT_UPLOAD_STATUS_AT_CAPTURE)
    }
}

/**
 * One documentary opening balance, posted once at this branch. The supplier revision is
 * its observed storage generation. All documentary fields are explicit and immutable;
 * an explicitly supplied empty paymentTerms means the source specifies no terms.
 * Identity, actor, recording time and policy are supplied by the protected master.
 */
@Serializable
public data class LocalRecordOpeningSupplierObligationV1(
    public val obligationId: DomainId,
    public val supplierId: DomainId,
    public val expectedSupplierRevision: Revision,
    public val sourceEvidenceId: DomainId,
    public val sourceReference: String,
    public val sourceDocument: LocalOpeningSupplierDocumentaryEvidenceV1,
    public val openingDate: BusinessDate,
    public val amount: Money,
    public val paymentTerms: String,
    public val reasonCode: String,
) {
    init {
        require(expectedSupplierRevision.value >= 1)
        require(amount.currency == Currency.EGP && amount.minor > 0)
        normalizedPurchaseReference(sourceReference)
        openingSupplierObligationTerms(paymentTerms)
        purchasingReason(reasonCode)
    }
}

/** Original debt and supplier description, with the original protected recording identity. */
@Serializable
public data class LocalOpeningSupplierObligationViewV1(
    public val id: DomainId,
    public val revision: Revision,
    public val supplierId: DomainId,
    public val supplierRevision: Revision,
    public val supplierNames: LocalNamesV1,
    public val sourceEvidenceId: DomainId,
    public val sourceReference: String,
    public val sourceDocument: LocalOpeningSupplierDocumentaryEvidenceV1,
    public val sourceDocumentMetadata: LocalOpeningSupplierDocumentaryMetadataV1,
    public val openingDate: BusinessDate,
    public val amount: Money,
    public val paymentTerms: String,
    public val reasonCode: String,
    public val operationId: OperationId,
    public val actorId: DomainId,
    public val recordedAt: UtcInstant,
    public val policyRevision: Revision,
) {
    init {
        require(revision == Revision(1) && supplierRevision.value >= 1)
        require(amount.currency == Currency.EGP && amount.minor > 0)
        normalizedPurchaseReference(sourceReference)
        openingSupplierObligationTerms(paymentTerms)
        purchasingReason(reasonCode)
        val documentBytes = sourceDocument.text.encodeToByteArray(throwOnInvalidSequence = true)
        require(sourceDocumentMetadata.evidenceId == sourceEvidenceId && sourceDocumentMetadata.ownerObligationId == id &&
            sourceDocumentMetadata.supplierId == supplierId && sourceDocumentMetadata.captureOperationId == operationId &&
            sourceDocumentMetadata.capturedBy == actorId && sourceDocumentMetadata.capturedAt == recordedAt &&
            sourceDocumentMetadata.byteSize == documentBytes.size && sourceDocumentMetadata.sha256 == sha256(documentBytes).value)
    }
}

/** Supplier-filtered pages scan bounded branch keys; nextAfter is the last scanned key. */
@Serializable
public data class LocalOpeningSupplierObligationQueryV1(
    public val id: DomainId? = null,
    public val supplierId: DomainId? = null,
    public val after: DomainId? = null,
    public val limit: Int = LocalOpeningSupplierObligationProfile.MAX_PAGE,
) {
    init { require(limit in 1..LocalOpeningSupplierObligationProfile.MAX_PAGE && (id == null || after == null)) }
}

/** Amounts and documentary details require current purchasing and inventory-cost access. */
@Serializable
public data class LocalOpeningSupplierObligationPageV1(
    public val query: LocalOpeningSupplierObligationQueryV1,
    public val entries: List<LocalOpeningSupplierObligationViewV1>,
    public val nextAfter: DomainId?,
    public val availability: LocalPurchasingReadAvailabilityV1 = LocalPurchasingReadAvailabilityV1.AVAILABLE,
) {
    init {
        require(entries.size <= query.limit && entries.map { it.id }.distinct().size == entries.size)
        require(entries.zipWithNext().all { (left, right) -> left.id.value < right.id.value })
        require(entries.all { entry -> (query.id == null || entry.id == query.id) &&
            (query.supplierId == null || entry.supplierId == query.supplierId) &&
            (query.after == null || entry.id.value > query.after.value) })
        require(query.id == null || nextAfter == null && entries.size <= 1)
        require(nextAfter == null || query.id == null && (query.after == null || nextAfter.value > query.after.value) &&
            entries.all { it.id.value <= nextAfter.value })
        require(availability == LocalPurchasingReadAvailabilityV1.AVAILABLE || entries.isEmpty() && nextAfter == null)
    }
}

/** Minimal retained outcome; debt values and documentary evidence stay behind the read route. */
@Serializable
public data class LocalOpeningSupplierObligationResultV1(
    public val code: String,
    public val id: DomainId,
    public val revision: Revision?,
) {
    init {
        require(code == LocalOpeningSupplierObligationProfile.RECORDED || code in openingSupplierObligationRejections)
        require(if (code == LocalOpeningSupplierObligationProfile.RECORDED) revision == Revision(1) else revision == null)
    }
}

