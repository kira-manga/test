    public fun query(value: LocalOpeningSupplierObligationQueryV1): StoredBytes =
        openingSupplierObligationEncode(value, LocalOpeningSupplierObligationQueryV1.serializer(), LocalOpeningSupplierObligationProfile.MAX_INPUT_BYTES)
    public fun decodeQuery(bytes: StoredBytes): LocalOpeningSupplierObligationQueryV1 =
