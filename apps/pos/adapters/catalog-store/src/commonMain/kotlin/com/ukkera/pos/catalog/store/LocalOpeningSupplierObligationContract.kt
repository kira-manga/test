        openingSupplierObligationDecode(bytes, LocalOpeningSupplierObligationResultV1.serializer(), LocalOpeningSupplierObligationProfile.MAX_INPUT_BYTES)
}

internal val openingSupplierObligationRejections: Set<String> = setOf(
    "purchasing.opening_obligation_identity_used",
    "purchasing.opening_obligation_duplicate_source",
    "purchasing.opening_obligation_duplicate_reference",
    "purchasing.opening_obligation_supplier_required",
    "purchasing.opening_obligation_stale_supplier",
)

internal fun openingSupplierObligationTerms(value: String) {
    require(value.length <= 256 && (value.isEmpty() || value.isNotBlank()) &&
        value.none { it.code < 0x20 || it.code == 0x7f })
}

internal fun <T> openingSupplierObligationEncode(value: T, serializer: KSerializer<T>, maximum: Int): StoredBytes {
    val bytes = purchasingJson.encodeToString(serializer, value).encodeToByteArray(throwOnInvalidSequence = true)
    require(bytes.size <= maximum)
    return StoredBytes(bytes)
}

internal fun <T> openingSupplierObligationDecode(bytes: StoredBytes, serializer: KSerializer<T>, maximum: Int): T {
    require(bytes.size <= maximum)
    val input = bytes.copyBytes().decodeToString(throwOnInvalidSequence = true)
    requireUniqueOpeningSupplierObligationJsonFields(input)
    return purchasingJson.decodeFromString(serializer, input)
}
