package com.ukkera.pos.recovery.store

import com.ukkera.pos.types.DomainId

/**
 * Master full-state backup (format "UKMSB" v1) ports. These are additive to the legacy
 * [LocalBackupStore] archive format, which is unchanged. Every port is supplied by the Master's
 * real platform composition; there are no accepting or no-op defaults. A port value is never
 * authorization: the Master owner decides when capture/restore may run.
 */

/** Exact facts the Master's own native owner observed at its serialized capture cut. */
public class MasterStateCaptureFacts(
    public val organizationId: DomainId,
    public val companyId: DomainId,
    public val branchId: DomainId,
    /** The installation the snapshot belongs to; restore approval must bind the same id. */
    public val installationId: DomainId,
    public val schemaVersion: Int,
    /** Room identity hash read from the captured database itself (32 lowercase hex). */
    public val roomIdentityHash: String,
    /** Native history anchor at the capture cut: generation and canonical record digest. */
    public val historyGeneration: Long,
    public val historyRecordDigest: String,
    public val snapshotBytes: Long,
    public val snapshotSha256: String,
) {
    init {
        require(schemaVersion > 0 && historyGeneration >= 0)
        require(roomIdentityHash.length == 32 && roomIdentityHash.all(::lowerHexChar))
        require(isSha256(historyRecordDigest) && isSha256(snapshotSha256))
        require(snapshotBytes in MIN_SNAPSHOT_BYTES..MAX_SNAPSHOT_BYTES)
    }
    override fun toString(): String = "MasterStateCaptureFacts([REDACTED])"
}

/** One private consistent copy, owned by the capture invocation until [discard]. */
public interface MasterStateSnapshot {
    public val facts: MasterStateCaptureFacts
    /** Bounded read at [offset]; returns fewer bytes only at the end of the snapshot. */
    public suspend fun read(offset: Long, max: Int): ByteArray
    /** Remove the private copy; called on every outcome. */
    public suspend fun discard()
}

/**
 * The Master's serialized capture. The implementation MUST take the copy under the Master's own
 * writer exclusion (no live-file copy) and observe the native history anchor at that same cut.
 */
public fun interface MasterStateSnapshotSource {
    public suspend fun capture(): MasterStateSnapshot
}

/**
 * Platform recovery key custody (desktop: the service's non-exportable OS key; Android: a
 * non-exportable Android Keystore key). AEAD with associated data; [open] MUST throw on any
 * authentication failure. Missing/locked keys throw; a replacement key is never generated by
 * [open]. [keyId] is a stable non-secret label recorded in each manifest.
 */
public interface MasterBackupKeyCustody {
    public val keyId: String
    public suspend fun seal(aad: ByteArray, plaintext: ByteArray): ByteArray
    public suspend fun open(aad: ByteArray, sealed: ByteArray): ByteArray
}

/** Durable private archive storage. Publication is atomic; partial archives are never listed. */
public interface MasterBackupVault {
    public suspend fun archiveIds(): List<DomainId>
    public suspend fun create(backupId: DomainId): MasterBackupArchiveWriter
    public suspend fun open(backupId: DomainId): MasterBackupArchiveReader
    public suspend fun delete(backupId: DomainId)
    /** Durable chain head (newest published manifest digest + sequence); null when none. */
    public suspend fun readChainHead(): ByteArray?
    public suspend fun writeChainHead(bytes: ByteArray)
}

public interface MasterBackupArchiveWriter {
    public suspend fun append(bytes: ByteArray)
    /** Force and atomically publish the complete archive. */
    public suspend fun publish()
    /** Remove the unpublished partial archive. */
    public suspend fun abort()
}

public interface MasterBackupArchiveReader {
    /** Exactly [count] bytes, or throw at a truncated archive. */
    public suspend fun readExactly(count: Int): ByteArray
    /** True when no further bytes remain. */
    public suspend fun atEnd(): Boolean
    public suspend fun close()
}

public enum class MasterRestoreTargetCondition {
    /** No installation and no prior restore candidate exist at the target. */
    FRESH,
    /** Only quarantined (refused) candidates exist; no live or held state. */
    QUARANTINED,
    /** Live state or a held candidate exists; restore refuses and changes nothing. */
    OCCUPIED,
}

/**
 * Fresh/quarantined restore destination. It never replaces a live database: [install] publishes
 * a HELD candidate, not an admitted Master. Activation of a held candidate as a writer requires
 * the separate native history/key-anchor rebind (#54) and is not performed here.
 */
public interface MasterRestoreTarget {
    public suspend fun condition(): MasterRestoreTargetCondition
    public suspend fun beginStage(backupId: DomainId): MasterRestoreStage
}

public interface MasterRestoreStage {
    public suspend fun append(bytes: ByteArray)
    /** Force the staged bytes, then natively observe them (hash, integrity, schema, identity). */
    public suspend fun observe(): MasterRestoredObservation
    /** Publish the verified staged copy as a HELD candidate together with [heldRecord]. */
    public suspend fun installHeld(heldRecord: ByteArray)
    /** Move the staged copy and [reason] into quarantine; never deleted silently. */
    public suspend fun quarantine(reason: MasterRestoreRefusal)
    /** Remove only an untouched/empty stage. */
    public suspend fun abort()
}

/** Native observation of the staged restored database bytes. */
public class MasterRestoredObservation(
    public val bytes: Long,
    public val sha256: String,
    public val integrityOk: Boolean,
    public val schemaVersion: Int,
    public val roomIdentityHash: String,
)

/**
 * Head approval for one restore. The approval id must resolve, through [MasterRestoreAuthority],
 * to a committed authenticated head lifecycle decision of the SAME installation. Possessing an
 * archive file or a UI flag is never approval.
 */
public class MasterRestoreApproval(
    public val approvalId: DomainId,
    public val installationId: DomainId,
) {
    override fun toString(): String = "MasterRestoreApproval([REDACTED])"
}

public fun interface MasterRestoreAuthority {
    /** True only for a durable, authenticated head approval of exactly this installation. */
    public suspend fun verify(approval: MasterRestoreApproval, backupId: DomainId, installationId: DomainId): Boolean
}

internal fun lowerHexChar(value: Char): Boolean = value in '0'..'9' || value in 'a'..'f'
internal const val MIN_SNAPSHOT_BYTES: Long = 512
internal const val MAX_SNAPSHOT_BYTES: Long = 8L * 1024 * 1024 * 1024
