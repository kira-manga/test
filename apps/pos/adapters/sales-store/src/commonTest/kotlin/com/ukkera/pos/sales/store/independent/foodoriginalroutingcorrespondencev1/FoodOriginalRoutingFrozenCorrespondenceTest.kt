        assertEquals(1533, quotation.signedPublication.encodeToByteArray().size)
        assertContentEquals(f.SIGNED_PUBLICATION.encodeToByteArray(), quotation.signedPublication.encodeToByteArray())
    }

    private fun attemptMutation(action: () -> Unit, reread: () -> Unit) {
        runCatching(action)
        reread()
    }

    private data class Rejection(val name: String, val invalidShape: Boolean = false,
        val change: (LocalFoodRecipeSnapshotV1) -> LocalFoodRecipeSnapshotV1)

    /** First armed complete read returns old entries; subsequent reads observe the prescribed delta. */
    private class FirstCompleteReadSources(initial: List<LocalFoodSourceReferenceV1>,
        private val later: List<LocalFoodSourceReferenceV1>) : AbstractList<LocalFoodSourceReferenceV1>() {
        private val holder = initial.toMutableList()
        private val seen = BooleanArray(initial.size)
        private var armed = false
        var changedAfterCompleteRead: Boolean = false
            private set
        override val size: Int get() = holder.size
        override fun get(index: Int): LocalFoodSourceReferenceV1 {
            val value = holder[index]
            if (armed && !changedAfterCompleteRead) {
                seen[index] = true
                if (seen.all { it }) {
                    changedAfterCompleteRead = true
                    holder.clear()
                    holder.addAll(later)
                }
            }
            return value
        }
        fun arm() { armed = true }
    }
