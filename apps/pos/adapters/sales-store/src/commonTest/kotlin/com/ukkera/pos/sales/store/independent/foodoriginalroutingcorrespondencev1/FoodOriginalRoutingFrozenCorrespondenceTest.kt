            f.u(7), Revision(7), f.u(8), f.modifiers(), f.DESCRIPTION, f.q(13, 400, 2), f.q(13, 150, 2),
            f.u(9), f.ingredients(), f.SIGNED_PUBLICATION, listOf(f.u(18), f.u(17)), f.originalSources(),
        ), listOf(
            quotation.portionId, quotation.activity, quotation.channel, quotation.recipeId, quotation.recipeRevision,
