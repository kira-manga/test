    @Test
    fun FORC_006_InputReturnedAndCaptureOrderListsRetainCheckedFacts() {
        val quotation = f.quotation()
        val modifiers = f.modifiers().toMutableList()
        val ingredients = f.ingredients().toMutableList()
        val routes = f.routesA().toMutableList()
        val sources = (f.originalSources() + f.sourcesA()).toMutableList()
        val candidate = f.a0(modifierIds = modifiers, ingredientValues = ingredients, routes = routes, sources = sources)
        val expected = f.a0()
        val checked = FoodRecipeRouting.requireOriginalFacts(quotation, candidate)
        assertCandidate(expected, candidate)
        assertQuotation(quotation)
        val reread = { assertCandidate(expected, checked); assertQuotation(quotation) }
        reread()
        for (holder in listOf<MutableList<*>>(modifiers, ingredients, routes, sources)) {
            holder.reverse()
            reread()
            holder.clear()
            reread()
        }
        for (collection in listOf<() -> List<*>>(
            { checked.modifierIds }, { checked.ingredients }, { checked.routes }, { checked.sources },
        )) {
            attemptMutation({ (collection() as MutableList<*>).clear() }, reread)
            attemptMutation({ (collection() as MutableList<*>).reverse() }, reread)
            attemptMutation({ (collection() as MutableList<*>).removeAt(0) }, reread)
        }
        captureOrder()
    }

    private fun captureOrder() {
        val quotation = f.quotation()
        val expected = f.a0()
        val holder = FirstCompleteReadSources(expected.sources,
            f.originalSources() + listOf(f.ra21, f.sa23, f.sa22.copy(operationId = OperationId(f.u(90).value))))
        val candidate = f.a0(sources = holder)
        assertCandidate(expected, candidate)
        assertTrue(candidate.sources === holder,
            "Public construction captured the list: checker capture-order coverage is UNBOUND")
        holder.arm()
        val checked = FoodRecipeRouting.requireOriginalFacts(quotation, candidate)
        assertTrue(holder.changedAfterCompleteRead,
            "The armed complete source read was not observed: capture-order coverage is UNBOUND")
        assertCandidate(expected, checked)
        assertQuotation(quotation)
        println("FORC-006/capture-order: CHECKER_CAPTURE_EXERCISED")
    }

    private fun reject(case: String, variants: List<Rejection>) {
        for (variant in variants) {
            val quotation = f.quotation()
            val base = f.a0()
            val construction = runCatching { variant.change(base) }
            if (construction.isFailure) {
                assertTrue(variant.invalidShape, case + "/" + variant.name + ": unexpected constructor refusal; checker NOT_RUN")
                assertNull(construction.getOrNull())
                assertCandidate(f.a0(), base)
                assertQuotation(quotation)
                println(case + "/" + variant.name + ": CONSTRUCTOR_REJECTION; CHECKER_UNBOUND")
                continue
            }
            val candidate = construction.getOrThrow()
            val callTime = candidate.copy(modifierIds = candidate.modifierIds.toList(),
                ingredients = candidate.ingredients.toList(), routes = candidate.routes.toList(), sources = candidate.sources.toList())
            val result = runCatching { FoodRecipeRouting.requireOriginalFacts(quotation, candidate) }
            assertTrue(result.isFailure, case + "/" + variant.name + " must fail at checker")
            assertNull(result.getOrNull())
            assertCandidate(callTime, candidate)
            assertCandidate(f.a0(), base)
            assertQuotation(quotation)
            println(case + "/" + variant.name + ": CHECKER_REJECTION")
        }
    }

    private fun firstIngredient(candidate: LocalFoodRecipeSnapshotV1,
        change: (LocalFoodIngredientV1) -> LocalFoodIngredientV1): LocalFoodRecipeSnapshotV1 =
        candidate.copy(ingredients = listOf(change(candidate.ingredients[0]), candidate.ingredients[1]))

    private fun prefixReference(candidate: LocalFoodRecipeSnapshotV1, index: Int,
        replacement: LocalFoodSourceReferenceV1): LocalFoodRecipeSnapshotV1 =
        candidate.copy(sources = candidate.sources.mapIndexed { at, source -> if (at == index) replacement else source })

    private fun suffix(candidate: LocalFoodRecipeSnapshotV1,
        sources: List<LocalFoodSourceReferenceV1>): LocalFoodRecipeSnapshotV1 =
        candidate.copy(sources = f.originalSources() + sources)

    private fun assertCandidate(expected: LocalFoodRecipeSnapshotV1, actual: LocalFoodRecipeSnapshotV1) {
        assertEquals(expected, actual)
        assertEquals(1533, actual.signedPublication.encodeToByteArray().size)
        assertContentEquals(expected.signedPublication.encodeToByteArray(), actual.signedPublication.encodeToByteArray())
    }

    private fun assertQuotation(quotation: LocalFoodRecipeQuotationV1) {
        assertEquals(f.quotationId, quotation.quotationId)
        assertEquals(listOf(
